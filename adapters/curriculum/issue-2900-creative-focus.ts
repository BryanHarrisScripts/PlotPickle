type TopicDocument = Readonly<{
  readonly topic: { readonly id: string; readonly title: string };
  readonly lessons: readonly CurriculumLesson[];
  readonly lessonCount: number;
  readonly sourceCount: number;
  readonly schemaVersion: string;
}>;

export function withIssue2900CreativeFocus(documents: readonly TopicDocument[]): readonly TopicDocument[] {
  const found = new Set<string>();
  const projected = documents.map((document) => ({
    ...document,
    lessons: document.lessons.map((lesson) => {
      const supplement = ISSUE_2900_CREATIVE_FOCUS.find((item) => item.lessonId === lesson.id);
      if (!supplement) return lesson;
      if (supplement.topic !== lesson.topic || document.topic.id !== lesson.topic) {
        throw new Error(`Creative Focus lesson topic mismatch: ${lesson.id}`);
      }
      if (found.has(lesson.id)) throw new Error(`Creative Focus duplicate lesson: ${lesson.id}`);
      found.add(lesson.id);
      return {
        ...lesson,
        sections: [...lesson.sections, {
          heading: supplement.heading,
          paragraphs: [...supplement.paragraphs],
          points: [...supplement.points],
        }, {
          heading: "Apply this to your story",
          paragraphs: ["Practice this craft technique on your approved story material. The suggested skill only proposes options; accept or reject them as the writer."],
          points: [supplement.exercise],
        }],
        tags: [...new Set([...lesson.tags, "Creative Focus", "agent craft", supplement.skillId])],
      };
    }),
  }));
  if (found.size !== ISSUE_2900_CREATIVE_FOCUS.length) {
    throw new Error(`Creative Focus attached ${found.size}/${ISSUE_2900_CREATIVE_FOCUS.length} lesson supplements.`);
  }
  return projected;
}

export function withIssue2900CreativeFocusLessons(lessons: readonly CurriculumLesson[]): readonly CurriculumLesson[] {
  const topics = [...new Set(lessons.map((lesson) => lesson.topic))];
  const documents = topics.map((topic) => {
    const topicLessons = lessons.filter((lesson) => lesson.topic === topic);
    return {
      schemaVersion: "2.0",
      topic: { id: topic, title: topic },
      lessonCount: topicLessons.length,
      sourceCount: topicLessons.flatMap((lesson) => lesson.sources).length,
      lessons: topicLessons,
    };
  });
  const enhanced = withIssue2900CreativeFocus(documents);
  const byId = new Map(enhanced.flatMap((document) => document.lessons).map((lesson) => [lesson.id, lesson]));
  if (byId.size !== lessons.length) throw new Error("Creative Focus lesson identity changed.");
  return lessons.map((lesson) => byId.get(lesson.id) ?? lesson);
}
