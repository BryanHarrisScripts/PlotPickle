#!/usr/bin/env node

import { execFile } from "node:child_process";
import { readFile } from "node:fs/promises";
import process from "node:process";
import { promisify } from "node:util";
import { bestEffortLiveBuzzActivity } from "./buzz-live-activity.mjs";

const exec = promisify(execFile);
const argv = process.argv.slice(2);
const argument = (name, fallback = "") => {
  const index = argv.indexOf(name);
  return index >= 0 && index + 1 < argv.length ? argv[index + 1] : fallback;
};
const reportPath = argument("--report");
const repository = argument("--repository", process.env.GITHUB_REPOSITORY || "BryanHarrisScripts/PlotPickle");
if (!reportPath) throw new Error("Use --report <writer-in-residence-report.json>.");

async function gh(...args) {
  const command = process.platform === "win32" ? "gh.exe" : "gh";
  const { stdout } = await exec(command, args, { windowsHide: true, maxBuffer: 4 * 1024 * 1024 });
  return stdout.trim();
}

function marker(fingerprint) {
  return `<!-- plotpickle-synthetic-writer:${fingerprint} -->`;
}

async function ensureLabels() {
  const labels = [
    ["synthetic-writer", "5319E7", "Feedback from PlotPickle's synthetic Writer-in-Residence, not a real customer"],
    ["product-feedback", "7057FF", "Product experience, usability or feature feedback"],
    ["needs-triage", "FBCA04", "Needs human product/engineering triage before repair"],
    ["experience:bug", "D93F0B", "Visible behaviour appears broken to the synthetic writer"],
    ["experience:friction", "E99695", "Usability friction encountered by the synthetic writer"],
    ["experience:confusion", "F9D0C4", "Concept, wording or navigation confusion"],
    ["experience:need", "C5DEF5", "Product capability or guidance need"],
    ["experience:abandonment-risk", "B60205", "Experience likely to make a writer stop or leave"],
  ];
  for (const [name, color, description] of labels) {
    await gh("label", "create", name, "--repo", repository, "--color", color, "--description", description, "--force");
  }
}

async function existingIssue(fingerprint) {
  const raw = await gh("issue", "list", "--repo", repository, "--state", "open", "--label", "synthetic-writer", "--limit", "100", "--json", "number,body,title,url");
  const issues = JSON.parse(raw || "[]");
  return issues.find((issue) => String(issue.body || "").includes(marker(fingerprint))) || null;
}

function issueBody(report, finding) {
  return [
    marker(finding.fingerprint),
    "## Synthetic Writer-in-Residence feedback",
    "",
    "> **Important:** This is synthetic product-research feedback generated by an AI writer persona. It is not a real customer report.",
    "",
    `**Persona:** ${report.persona?.name || "Writer-in-Residence"}`,
    `**Journey:** ${report.storySeed?.title || "Disposable synthetic story"}`,
    `**Kind:** ${finding.kind}`,
    `**Severity:** ${finding.severity}`,
    `**Route:** ${finding.route || "unknown"}`,
    `**Turn:** ${finding.turn || "unknown"}`,
    "",
    "### What the writer experienced",
    "",
    finding.summary,
    "",
    finding.expectation ? `**Expected as a writer:** ${finding.expectation}` : "",
    finding.impact ? `**Why it matters:** ${finding.impact}` : "",
    "",
    "### Visible evidence excerpt",
    "",
    "```text",
    String(finding.evidence || "No visible evidence excerpt recorded.").slice(0, 1500),
    "```",
    "",
    "### Triage boundary",
    "",
    "This issue is product feedback first. Do not treat the synthetic writer's interpretation as proof of a code defect. A human or deterministic UAT pass should reproduce technical failures before adding `uat:auto-repair`. Experience needs, wording, navigation and usability findings may be resolved as product-design work without entering the automated repair queue.",
  ].filter(Boolean).join("\n");
}

function buzzFindingEvent(finding) {
  const visual = finding.source === "rendered-visual-observer";
  return {
    type: visual ? "visual.finding" : "writer.feedback",
    actorId: visual ? "luma-glassfern" : "avery-north",
    summary: String(finding.summary || "Writer-in-Residence finding").slice(0, 650),
    severity: finding.severity || "medium",
    target: finding.route || "writer-in-residence",
    verified: visual,
    actionable: finding.actionable === true,
    evidence: finding.fingerprint ? [{ label: "Writer finding", ref: finding.fingerprint }] : [],
  };
}

async function mirrorGithubStatus(summary, ref) {
  await bestEffortLiveBuzzActivity({
    type: "github.status",
    actorId: "fen-copperwind",
    summary,
    severity: "info",
    target: repository,
    verified: true,
    actionable: false,
    evidence: ref ? [{ label: "GitHub", ref }] : [],
  });
}

async function main() {
  const report = JSON.parse(await readFile(reportPath, "utf8"));
  const findings = Array.isArray(report.promotedFindings) ? report.promotedFindings : [];
  if (!findings.length) {
    process.stdout.write("No Writer-in-Residence findings to report.\n");
    return;
  }
  await gh("auth", "status", "--hostname", "github.com");
  await ensureLabels();

  for (const finding of findings) {
    await bestEffortLiveBuzzActivity(buzzFindingEvent(finding));
    const current = await existingIssue(finding.fingerprint);
    const body = issueBody(report, finding);
    const kindLabel = `experience:${finding.kind}`;
    const labels = ["synthetic-writer", "product-feedback", "needs-triage"];
    if (["bug", "friction", "confusion", "need", "abandonment-risk"].includes(finding.kind)) labels.push(kindLabel);
    if (current) {
      await gh("issue", "comment", String(current.number), "--repo", repository, "--body", body);
      process.stdout.write(`Updated synthetic writer issue #${current.number}: ${finding.fingerprint}\n`);
      await mirrorGithubStatus(`Updated synthetic Writer-in-Residence issue #${current.number} from ${finding.fingerprint}.`, current.url || "");
      continue;
    }
    const titlePrefix = finding.kind === "bug" ? "Possible bug" : finding.kind === "need" ? "Need" : finding.kind.replaceAll("-", " ");
    const issueUrl = await gh(
      "issue", "create",
      "--repo", repository,
      "--title", `[Synthetic Writer] ${titlePrefix}: ${finding.summary.slice(0, 90)}`,
      "--body", body,
      ...labels.flatMap((label) => ["--label", label]),
    );
    process.stdout.write(`Created synthetic writer feedback: ${issueUrl}\n`);
    await mirrorGithubStatus(`Created synthetic Writer-in-Residence GitHub feedback for ${finding.fingerprint}.`, issueUrl);
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack || error.message : String(error));
  process.exitCode = 1;
});